LETTERS = dict(zip('ABCDEFGHIJKLMNOPQRSTUVWXYZ', '에이 비 씨 디 이 에프 지 에이치 아이 제이 케이 엘 엠 엔 오 피 큐 알 에스 티 유 브이 더블유 엑스 와이 제트'.split(), strict=True))
PHRASES = [(
    re.compile(r'(?<![A-Za-z])' + r'[\s-]+'.join(map(re.escape, phrase.split())) + r'(?![A-Za-z])', re.I),
    equivalent,
) for phrase, equivalent in ALIASES.items()]


def additions(text):
    terms = [equivalent for pattern, equivalent in PHRASES if pattern.search(text)]
    for acronym in set(re.findall(r'(?<![A-Za-z])(?:[A-Z]{2,5})(?![A-Za-z])', text)):
        if acronym not in {'I', 'II', 'III', 'HPC', 'LAB', 'KOREATECH', 'ETC', 'MS', 'OS'}:
            terms.append(''.join(LETTERS[letter] for letter in acronym))
    return tuple(terms)


